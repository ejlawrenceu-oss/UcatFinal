
public class UCAT19StudentGrades {
    public static void main(String[] args) {
        String[] names = {"Alice", "Bob", "Charlie"};
        int[] grades = {85, 70, 90};
        for (int i = 0; i < names.length; i++) {
            System.out.println(names[i] + ": " + grades[i]);
        }
    }
}
